"use strict";
function Tools({ account, trades, onAdd, onExport, onBackup, onRestore, onNewAccount }) { const [calc, setCalc] = useState({ symbol: 'XAUUSD', entry: '', sl: '', tp: '', lots: '0.01' }); const riskDistance = Math.abs(Number(calc.entry || 0) - Number(calc.sl || 0)); const riskUsd = riskFor(calc.entry, calc.sl, calc.lots, calc.symbol); const rewardUsd = rewardFor(calc.entry, calc.tp, calc.lots, calc.symbol); return React.createElement("section", null,
    React.createElement(PageHeading, { eyebrow: "TOOLS / UTILITIES", title: "Trading Tools", description: "Kalkulator risk dan reward.", action: React.createElement("button", { className: "icon-btn" },
            React.createElement(Settings2, { size: 18 })) }),
    React.createElement("div", { className: "tool-card featured" },
        React.createElement("div", { className: "tool-head" },
            React.createElement("div", { className: "tool-icon" },
                React.createElement(Target, null)),
            React.createElement("div", null,
                React.createElement("h2", null, "Risk calculator"),
                React.createElement("p", null, "Hitung risk, reward, dan persentase jarak harga sebelum entry."))),
        React.createElement("div", { className: "calc-grid compact-calc" },
            React.createElement("label", null,
                "Symbol",
                React.createElement(TSelect, { title: "Symbol", value: calc.symbol, options: SYMBOLS, onChange: v => setCalc({ ...calc, symbol: v }) })),
            React.createElement("label", null,
                "Entry",
                React.createElement("input", { inputMode: "decimal", value: calc.entry, onChange: e => setCalc({ ...calc, entry: e.target.value }), placeholder: "4158" })),
            React.createElement("label", null,
                "Lots",
                React.createElement("input", { type: "number", step: "0.01", value: calc.lots, onChange: e => setCalc({ ...calc, lots: e.target.value }) })),
            React.createElement("label", null,
                "Stop loss",
                React.createElement("input", { inputMode: "decimal", value: calc.sl, onChange: e => setCalc({ ...calc, sl: e.target.value }), placeholder: "4153" })),
            React.createElement("label", null,
                "Take profit",
                React.createElement("input", { inputMode: "decimal", value: calc.tp, onChange: e => setCalc({ ...calc, tp: e.target.value }), placeholder: "4163.5" }))),
        React.createElement("div", { className: "quick-values calculator-results" },
            React.createElement("div", null,
                React.createElement("span", null, "Risk amount"),
                React.createElement("strong", { className: "negative" }, money(riskUsd)),
                React.createElement("small", null, riskUsd ? 'Entry − SL × lots' : 'Isi entry + SL + lots')),
            React.createElement("div", null,
                React.createElement("span", null, "Reward"),
                React.createElement("strong", { className: "positive" }, money(rewardUsd)),
                React.createElement("small", null,
                    "R:R ",
                    riskUsd ? (rewardUsd / riskUsd).toFixed(2) : '—')),
            React.createElement("div", null,
                React.createElement("span", null, "Risk % formula"),
                React.createElement("strong", null, calc.entry && calc.sl ? `${(riskDistance / Number(calc.entry) * 100).toFixed(2)}%` : '—'),
                React.createElement("small", null, "distance / entry")))),
); }
