/* Halaman My Journal dan kartu trade */
"use strict";
function Journal({ account, trades, filters, setFilters, expanded, setExpanded, onAdd, onScan, onDelete, onClose, onEdit }) {
    const [addMenu, setAddMenu] = useState(false);
    const fileRef = useRef(null);
    const [openWeeks, setOpenWeeks] = useState({});
    const filtered = trades.filter(t => (filters.status === 'all' || t.status === filters.status) && (filters.side === 'all' || t.side === filters.side) && (!filters.search || t.symbol.toLowerCase().includes(filters.search.toLowerCase()) || String(t.setup || '').toLowerCase().includes(filters.search.toLowerCase())) && (!filters.date || dateOnly(t.date) === filters.date));
    const groups = filtered.reduce((acc, t) => { const key = dateOnly(t.date); (acc[key] || (acc[key] = [])).push(t); return acc; }, {});
    return React.createElement("section", null,
        React.createElement(PageHeading, { eyebrow: "LOGBOOK / TRADE HISTORY", title: "My Journal", description: `Semua transaksi akun ${account.name}.`, action: React.createElement("button", { className: "primary-btn compact", onClick: onAdd },
                React.createElement(Plus, { size: 16 }),
                " Add trade") }),
        React.createElement("div", { className: "journal-controls" },
            React.createElement("div", { className: "search-box" },
                React.createElement(Search, { size: 15 }),
                React.createElement("input", { value: filters.search, onChange: e => setFilters({ ...filters, search: e.target.value }), placeholder: "Cari symbol atau setup..." })),
            React.createElement(TSelect, { title: "Status", value: filters.status, options: [{ v: 'all', l: 'All status' }, { v: 'open', l: 'Open' }, { v: 'closed', l: 'Closed' }], onChange: v => setFilters({ ...filters, status: v }) }),
            React.createElement(TSelect, { title: "Arah", value: filters.side, options: [{ v: 'all', l: 'Long & Short' }, { v: 'Long', l: 'Long' }, { v: 'Short', l: 'Short' }], onChange: v => setFilters({ ...filters, side: v }) }),
            filters.date && React.createElement("button", { className: "filter-chip", onClick: () => setFilters({ ...filters, date: '' }) },
                filters.date,
                " ",
                React.createElement(X, { size: 12 }))),
        React.createElement("div", { className: "journal-toolbar" },
            React.createElement("button", { className: filters.status === 'all' ? 'pill active' : 'pill', onClick: () => setFilters({ ...filters, status: 'all' }) },
                "All ",
                React.createElement("span", null, trades.length)),
            React.createElement("button", { className: filters.status === 'open' ? 'pill active' : 'pill', onClick: () => setFilters({ ...filters, status: 'open' }) },
                "Open ",
                React.createElement("span", null, trades.filter(t => t.status === 'open').length)),
            React.createElement("button", { className: filters.status === 'closed' ? 'pill active' : 'pill', onClick: () => setFilters({ ...filters, status: 'closed' }) },
                "Closed ",
                React.createElement("span", null, trades.filter(t => t.status === 'closed').length)),
            React.createElement("span", { className: "results-count" },
                React.createElement(Filter, { size: 13 }),
                " ",
                filtered.length,
                " shown")),
        (() => { const isoOf = d => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; const weeks = {}; Object.keys(groups).forEach(day => { const d = new Date(`${day}T12:00`); d.setDate(d.getDate() - ((d.getDay() + 6) % 7)); const wk = isoOf(d); (weeks[wk] || (weeks[wk] = {}))[day] = groups[day]; }); return Object.keys(weeks).sort().reverse().map((wk, wi) => { const w = weeks[wk]; const list = Object.values(w).flat(); const pnl = list.reduce((x, t) => x + (t.status === 'closed' ? Number(t.pnl) || 0 : 0), 0); const st = new Date(`${wk}T12:00`); const en = new Date(st); en.setDate(st.getDate() + 6); const open = openWeeks[wk] !== undefined ? openWeeks[wk] : !!filters.date; const label = `${st.toLocaleDateString('en-GB', { day: 'numeric', month: 'short' })} - ${en.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' })}`; return React.createElement("div", { className: "week-block", key: wk },
            React.createElement("button", { className: "week-head", onClick: () => setOpenWeeks({ ...openWeeks, [wk]: !open }) },
                React.createElement("div", null,
                    React.createElement("strong", null, label),
                    React.createElement("small", null,
                        list.length,
                        " posisi")),
                React.createElement("b", { className: pnl >= 0 ? 'positive' : 'negative' },
                    pnl >= 0 ? '+' : '',
                    money(pnl, account.currency)),
                React.createElement(ChevronDown, { size: 17, className: open ? 'rotate' : '' })),
            open && Object.keys(w).sort((x, y) => y.localeCompare(x)).map(day => { const dp = w[day].reduce((x, t) => x + (t.status === 'closed' ? Number(t.pnl) || 0 : 0), 0); return React.createElement("div", { key: day },
                React.createElement("div", { className: "date-label" },
                    React.createElement("span", null, new Date(`${day}T12:00`).toLocaleDateString('id-ID', { weekday: 'long', day: '2-digit', month: 'long', year: 'numeric' })),
                    React.createElement("em", { className: dp >= 0 ? 'positive' : 'negative' },
                        dp >= 0 ? '+' : '',
                        money(dp, account.currency),
                        " \u00B7 ",
                        w[day].length,
                        " posisi")),
                w[day].map(t => React.createElement(TradeCard, { key: t.id, trade: t, expanded: expanded === t.id, onToggle: () => setExpanded(expanded === t.id ? null : t.id), onDelete: () => onDelete(t.id), onClose: () => onClose(t), onEdit: () => onEdit(t) }))); })); }); })(),
        !filtered.length && React.createElement("div", { className: "empty-state" },
            React.createElement(BookOpen, { size: 26 }),
            React.createElement("strong", null, "Tidak ada trade yang cocok"),
            React.createElement("span", null, "Ubah filter atau tambah transaksi baru.")),
        addMenu && React.createElement(AddMenu, { onClose: () => setAddMenu(false), onManual: () => { setAddMenu(false); onAdd(); }, onScreenshot: () => { setAddMenu(false); if (fileRef.current) { fileRef.current.value = ''; fileRef.current.click(); } } }),
        React.createElement("input", { ref: fileRef, type: "file", accept: "image/*", multiple: true, style: { display: 'none' }, onChange: e => { const f = e.target.files ? [...e.target.files] : []; if (f.length && onScan) onScan(f); } }),
        React.createElement("button", { className: addMenu ? "fab open" : "fab", "aria-label": "Tambah trade", "aria-expanded": addMenu, onClick: () => setAddMenu(!addMenu) },
            React.createElement(Plus, { size: 25 })));
}
function TradeCard({ trade, expanded, onToggle, onDelete, onClose, onEdit }) { var _a, _b, _c, _d; return React.createElement("div", { className: "trade-card", onClick: onToggle },
    React.createElement("div", { className: "trade-main" },
        React.createElement("div", { className: `side-dot ${trade.status === 'open' ? 'blue' : trade.pnl >= 0 ? 'green' : 'red'}` }),
        React.createElement("div", { className: "trade-info" },
            React.createElement("div", null,
                React.createElement("strong", null, trade.symbol),
                React.createElement("span", { className: trade.side === 'Long' ? 'side long' : 'side short' }, trade.side),
                React.createElement("span", { className: trade.status === 'open' ? 'side open' : 'side closed' }, trade.status === 'open' ? 'OPEN' : trade.exitMethod || 'CLOSED')),
            React.createElement("small", null,
                new Date(trade.date).toLocaleTimeString('id-ID', { hour: '2-digit', minute: '2-digit' }).replace(/\./g, ':'),
                " \u00B7 ",
                trade.setup || 'Tanpa setup')),
        React.createElement("div", { className: "trade-result" },
            trade.status === 'open' ? React.createElement(React.Fragment, null,
                React.createElement("strong", { className: "open-text" }, "OPEN"),
                React.createElement("small", null, "ACTIVE")) : React.createElement(React.Fragment, null,
                React.createElement("strong", { className: trade.pnl >= 0 ? 'positive' : 'negative' },
                    trade.pnl >= 0 ? '+' : '',
                    money(trade.pnl)),
                React.createElement("small", null, trade.pnl >= 0 ? 'WIN' : 'LOSS')),
            " "),
        React.createElement(ChevronDown, { size: 17, className: expanded ? 'rotate' : '' })),
    expanded && React.createElement("div", { className: "trade-detail" },
        React.createElement("div", null,
            React.createElement("span", null, "Entry / Exit"),
            React.createElement("b", null,
                trade.entry,
                " \u2192 ", (_a = trade.exit) !== null && _a !== void 0 ? _a : '—')),
        React.createElement("div", null,
            React.createElement("span", null, "Lots"),
            React.createElement("b", null, trade.lots)),
        React.createElement("div", null,
            React.createElement("span", null, "SL / TP"),
            React.createElement("b", null, (_b = trade.sl) !== null && _b !== void 0 ? _b : '—',
                " / ", (_c = trade.tp) !== null && _c !== void 0 ? _c : '—')),
        React.createElement("div", null,
            React.createElement("span", null, "Fees / Net P&L"),
            React.createElement("b", null,
                money(trade.fees || 0),
                " / ",
                money(trade.pnl))),
        React.createElement("div", null,
            React.createElement("span", null, "Review"),
            React.createElement("b", null, trade.review || 'Belum ada review')),
        trade.closeDate && React.createElement("div", null,
            React.createElement("span", null, "Closed at"),
            React.createElement("b", null, new Date(trade.closeDate).toLocaleString('id-ID').replace(/\./g, ':'))),
        ((_d = trade.screenshots) === null || _d === void 0 ? void 0 : _d.length) > 0 && React.createElement("div", { className: "screenshot-strip" }, trade.screenshots.map((src, i) => React.createElement("img", { key: i, src: src, alt: `Chart ${i + 1}` }))),
        trade.status === 'open' && React.createElement("button", { className: "secondary-btn detail-action", onClick: e => { e.stopPropagation(); onClose(); } }, "Tutup posisi"),
        React.createElement("div", { className: "trade-actions" },
            React.createElement("button", { className: "edit-btn", onClick: e => { e.stopPropagation(); onEdit(); } }, "\u270E Edit"),
            React.createElement("button", { className: "delete-btn", onClick: e => { e.stopPropagation(); onDelete(); } },
                React.createElement(Trash2, { size: 14 }),
                " Hapus")))); }
